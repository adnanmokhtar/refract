import { BadRequestException, Injectable } from '@nestjs/common';
import { exec, execFile } from 'child_process';
import { join } from 'path';
import { promisify } from 'util';
import { config } from '../config';

const run = promisify(exec);
const runFile = promisify(execFile);
const ASSET_ID = /^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$/i;

@Injectable()
export class ThumbnailService {
  // Storefront themes request thumbnails by size string, e.g. "320x320" or "640x".
  async resize(sourcePath: string, size: string): Promise<string> {
    const target = sourcePath.replace(/(\.[^./]+)$/, `_${size}$1`);
    await run(`convert "${sourcePath}" -auto-orient -resize ${size} "${target}"`, { timeout: 30_000 });
    return target;
  }

  // Width/height of a stored image, for the srcset the storefront builds.
  async dimensions(storedPath: string): Promise<{ width: number; height: number }> {
    if (!storedPath.startsWith(config.storage.uploads)) {
      throw new BadRequestException('not an upload');
    }
    const { stdout } = await runFile('identify', ['-format', '%w %h', storedPath], { timeout: 10_000 });
    const [width, height] = stdout.trim().split(' ').map(Number);
    return { width, height };
  }

  // Nightly CDN job: re-encode every original to WebP. Originals are keyed by asset id,
  // so both paths here are generated by us.
  async toWebp(assetId: string): Promise<string> {
    if (!ASSET_ID.test(assetId)) throw new BadRequestException('invalid asset id');
    const source = join(config.storage.uploads, 'originals', `${assetId}.png`);
    const target = join(config.storage.uploads, 'webp', `${assetId}.webp`);
    await runFile('cwebp', ['-quiet', '-q', '80', source, '-o', target], { timeout: 60_000 });
    return target;
  }
}
